import assert from 'node:assert/strict'
import { waitForValue } from './wait-for-value.mjs'

// Run against the installed WebView with the disposable 120-work library.
export async function exerciseLibraryLayout(page) {
  const button = (name) => page.getByRole('button', { name, exact: true })
  const search = page.getByLabel('搜索作品')
  const details = page.getByRole('complementary', { name: '所选作品操作' })
  const tags = details.getByLabel('作品标签')
  const priorSize = await page.evaluate(() => ({ width: innerWidth, height: innerHeight }))
  await button('作品库').click()
  try {
    await page.setViewportSize({ width: 1190, height: 772 })
    await search.fill('旧版测试作品')
    await details.getByText('旧版测试作品', { exact: true }).waitFor()
    const cover = await page.locator('.gallery-single .thumb').boundingBox()
    const side = await details.boundingBox()
    assert.ok(cover.width > 380 && side.x >= cover.x + cover.width && Math.abs(side.y - cover.y) < 6)
    const input = await tags.boundingBox()
    const save = await details.getByRole('button', { name: '保存标签' }).boundingBox()
    assert.ok(Math.abs(input.y - save.y) < 2 && save.x >= input.x + input.width)

    await tags.fill('晨光，远景,晨光')
    await tags.press('Enter')
    await waitForValue(async () => (await tags.inputValue()) === '晨光，远景', 'normalized saved tags')
    await button('收藏作品').click()
    await button('取消收藏').waitFor()
    await button('已收藏').click()
    await details.getByText('旧版测试作品', { exact: true }).waitFor()
    await button('归档作品').click()
    await details.waitFor({ state: 'detached' })
    await button('已归档').click()
    assert.equal(await tags.inputValue(), '晨光，远景')
    await button('移出归档').click()
    await details.waitFor({ state: 'detached' })
    await button('当前作品').click()
    await button('取消收藏').click()
    await button('收藏作品').waitFor()
    await tags.fill('')
    await tags.press('Enter')
    await waitForValue(() => button('保存标签').isDisabled(), 'tag removal')

    await search.fill('gallery-240')
    const cards = page.locator('.gallery .card')
    await waitForValue(async () => (await cards.count()) === 60, 'paged results')
    const second = cards.nth(1)
    const before = await second.boundingBox()
    const title = await second.locator('b').innerText()
    await second.focus()
    await second.press('Space')
    await details.getByText(title, { exact: true }).waitFor()
    assert.equal(await second.getAttribute('aria-pressed'), 'true')
    assert.equal((await second.boundingBox()).y, before.y)

    await page.setViewportSize({ width: 760, height: 540 })
    const compactInput = await tags.boundingBox()
    const compactBrowser = await page.locator('.library-browser').boundingBox()
    assert.ok(compactInput.x >= compactBrowser.x + compactBrowser.width && compactInput.y + compactInput.height < 540)
    await page.setViewportSize({ width: 620, height: 600 })
    await cards.nth(21).click()
    await details.getByText(await cards.nth(21).locator('b').innerText(), { exact: true }).waitFor()
    const strip = await page.locator('.library-browser').boundingBox()
    const compact = await details.boundingBox()
    assert.ok(compact.y >= strip.y + strip.height - 1 && compact.y - (strip.y + strip.height) < 20)
    assert.ok(await page.locator('.library-results').evaluate((el) => el.scrollLeft > 0))
    assert.ok(await page.locator('.library-page').evaluate((el) => el.scrollWidth <= el.clientWidth + 1))
    await search.fill('这一项没有任何匹配')
    await details.waitFor({ state: 'detached' })
    await button('清除筛选').click()
  } finally {
    await page.setViewportSize(priorSize)
  }
  console.log('Library layout passed: single and paged results, narrow filmstrip, keyboard selection, tags, favorite, archive and empty filters.')
}
